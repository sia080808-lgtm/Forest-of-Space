# Split the SRS-sheet small-neighbour sprites into a body layer and moving parts (legs, wings, antennae) with pivots.
# Body = morphological opening of the alpha mask (thin parts removed), the largest blob, grown 2 px. Every thin piece
# left over is a part; its pivot is the part pixel nearest the body. Type by position: wings (root fly, above the
# body), antennae (front = left side, above the body middle), legs (below). Mealybug wax spines (above the body) stay in
# the body layer (SRS D04.24: do not make the wax spines into legs). Output per sprite: <name>-body.png, <name>-parts.png
# (an atlas, one cell per part) and app/src/main/assets/web/creature-rig.js with all parts.
import json,numpy as np
from PIL import Image
from scipy import ndimage as nd
D='app/src/main/assets/web/assets/forest/creatures/'
CFG={'spidermite':{'r':15,'mite':True},'predatory-mite':{'r':15,'mite':True},'ladybird':{'r':15},'soil-mite':{'r':15,'mite':True},'root-gnat':{'r':9,'wings':True},'mealybug':{'r':6,'wax':True},'pillbug':{'r':7,'antennaLeft':2},'rove-beetle':{'r':6,'antennaLeft':3,'tailStatic':True}}
def disk(r):yy,xx=np.mgrid[-r:r+1,-r:r+1];return xx*xx+yy*yy<=r*r
meta={}
for name,c in CFG.items():
    im=Image.open(D+name+'.png').convert('RGBA');a=np.array(im);al=a[...,3]>40;h,w=al.shape
    body=nd.binary_opening(al,structure=disk(c['r']));lab,n=nd.label(body);body=lab==(1+int(np.argmax(nd.sum(body,lab,range(1,n+1)))))
    body=nd.binary_dilation(body,iterations=2)&al;ys,xs=np.nonzero(body);cy,cx=ys.mean(),xs.mean();top=ys.min()
    app=al&~body;lab2,n2=nd.label(app,structure=np.ones((3,3)));dist=nd.distance_transform_edt(~body)
    parts=[];static=np.zeros_like(al);small=[]
    for k in range(1,n2+1):
        m=lab2==k;size=int(m.sum())
        if size<25:small.append(m);continue
        py,px=np.nonzero(m);j=int(np.argmin(dist[py,px]));pvx,pvy=int(px[j]),int(py[j])
        bx0,by0,bx1,by1=int(px.min()),int(py.min()),int(px.max())+1,int(py.max())+1
        if c.get('mite'): t='leg'  # mites have no antennae; the front pair are legs
        elif c.get('wings') and by0<top and (bx1-bx0)>60: t='wing'
        elif pvy<cy and pvx<cx-(xs.max()-xs.min())*.2: t='antenna'
        elif c.get('wax') and pvy<cy: static|=m;continue
        elif pvy<cy-(ys.max()-ys.min())*.15 and not c.get('wings'): t='antenna' if pvx<cx else 'leg'
        else: t='leg'
        parts.append({'type':t,'x':bx0,'y':by0,'w':bx1-bx0,'h':by1-by0,'px':pvx,'py':pvy,'_m':m})
    # small leftover fragments (leg tips cut off by crossings) join the nearest part within 6 px, else stay with the body
    for m in small:
        near=nd.binary_dilation(m,iterations=6);best=max(parts,key=lambda p:int((near&p['_m']).sum()),default=None)
        if best is not None and (near&best['_m']).any():best['_m']=best['_m']|m
        else:static|=m
    if c.get('tailStatic'):   # thin abdomen-tip pieces behind and above the body centre belong to the body
        keep_=[]
        for p in parts:
            if p['px']>cx and p['py']<cy: static|=p['_m']
            else: keep_.append(p)
        parts=keep_
    if c.get('antennaLeft'):  # the frontmost pieces (sheet sprites face left) are antennae / mouthparts
        for p in sorted(parts,key=lambda p:p['px'])[:c['antennaLeft']]: p['type']='antenna'
    legs=sorted([p for p in parts if p['type']=='leg'],key=lambda p:p['px'])
    for i,p in enumerate(legs):p['group']=i%2
    keep=(body|static)[...,None]
    Image.fromarray(np.where(keep,a,0).astype(np.uint8),'RGBA').save(D+name+'-body.png')
    # parts atlas: every part in its own cell (its own pixels only, grown 2 px into the body so a rotated root never gaps),
    # laid out left to right; sx,sy = cell in the atlas, x,y = where it sits on the sprite
    cells=[];X=0
    for p in parts:
        g=nd.binary_dilation(p.pop('_m'),iterations=2)&al;py_,px_=np.nonzero(g);x0,y0,x1,y1=int(px_.min()),int(py_.min()),int(px_.max())+1,int(py_.max())+1
        cell=np.where(g[y0:y1,x0:x1,None],a[y0:y1,x0:x1],0).astype(np.uint8);p.update(x=x0,y=y0,w=x1-x0,h=y1-y0,sx=X,sy=0);cells.append(cell);X+=x1-x0+2
    H=max(c_.shape[0] for c_ in cells);atlas=np.zeros((H,max(1,X),4),np.uint8)
    for p,c_ in zip(parts,cells):atlas[0:c_.shape[0],p['sx']:p['sx']+c_.shape[1]]=c_
    Image.fromarray(atlas,'RGBA').save(D+name+'-parts.png')
    meta[name]={'w':w,'h':h,'parts':parts}
    print(name,{t:sum(1 for p in parts if p['type']==t) for t in ('leg','wing','antenna')})
with open('app/src/main/assets/web/creature-rig.js','w') as f: f.write("// generated by tools/rig-neighbours.py: moving parts (pivot px,py; source box x,y,w,h) of the small-neighbour sprites\n(function(root){const RIG="+json.dumps(meta,separators=(',',':'))+";if(typeof module==='object')module.exports=RIG;else root.ForestCreatureRig=RIG;})(globalThis);\n")
